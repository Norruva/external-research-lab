"""Compare the aasforge router with an AAS API Part 2 OpenAPI collection and write a coverage report.

    python tools/api_coverage.py path/to/Entire-API-Collection/V3.2.yaml [-o docs/API-COVERAGE.md]

Every operation in the spec is instantiated with sample path parameters and matched against the real
router, so the report reflects what the server dispatches, not what a hand-kept list claims. The single
shell (``/aas``) and single submodel (``/submodel``) service interfaces are matched through the
repository superpaths (``/shells/{id}``, ``/submodels/{id}``) that serve them in a repository server.
Needs PyYAML (development only).
"""
from __future__ import annotations

import argparse
import collections
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from aasforge.app import Config, Forge  # noqa: E402
from aasforge.http import HttpError  # noqa: E402

SAMPLES = {'idShortPath': 'Cell.Voltage', 'handleId': 'h1', 'packageId': 'p1'}
INTERFACES = (('/aas', '/shells/aW'), ('/submodel', '/submodels/aW'))


def concrete(path: str) -> str:
    return re.sub(r'\{(\w+)\}', lambda m: SAMPLES.get(m.group(1), 'aW'), path)


def shape(path: str) -> str:
    return re.sub(r'\{[^}]+\}', '{}', path)


def candidates(path: str):
    """(concrete path, expected route shape, mount) for the path and its repository mount point."""
    yield concrete(path), shape(path), None
    for prefix, mounted in INTERFACES:
        if path == prefix or path.startswith(prefix + '/'):
            rest = path[len(prefix):]
            yield mounted + concrete(rest), shape(mounted.replace('aW', '{}') + rest), mounted.split('/')[1]


def analyse(spec: dict):
    router = Forge(Config(database=':memory:')).api.router
    rows = []
    for path, item in spec['paths'].items():
        for method, operation in item.items():
            if method not in ('get', 'post', 'put', 'patch', 'delete'):
                continue
            served, via = None, None
            for candidate, expected, mount in candidates(path):
                try:
                    _, _, pattern = router.match(method.upper(), candidate)
                except HttpError:
                    continue
                if shape(pattern) == expected:      # a looser route catching the path does not count
                    served, via = pattern, mount
                    break
            rows.append({'tag': (operation.get('tags') or ['(untagged)'])[0], 'method': method.upper(), 'path': path,
                         'operationId': operation.get('operationId'), 'served': served, 'via': via})
    return rows


def extensions(router, spec: dict):
    """Router patterns no spec operation maps to: aasforge additions."""
    used = {r['served'] for r in analyse(spec) if r['served']}
    return sorted({(m, p) for m, _, _, _, p in router.routes if p not in used})


def report(spec: dict, rows: list, title: str, source: str = '') -> str:
    by_tag = collections.OrderedDict()
    for row in rows:
        by_tag.setdefault(row['tag'], []).append(row)
    covered = sum(1 for r in rows if r['served'])
    out = [f'# API coverage: {title}', '',
           f'Generated by `tools/api_coverage.py` from the official OpenAPI collection '
           f'(`{spec.get("info", {}).get("title", "AAS API")}` {spec.get("info", {}).get("version", "")}). '
           'Each operation is instantiated with sample parameters and dispatched through the real router.'
           + (f' Source: {source}.' if source else ''), '',
           '"Served" means the route exists with a handler; behaviour is covered by `tests/test_api.py`, not by '
           'this report.', '',
           f'**{covered} / {len(rows)} operations served** '
           f'({100 * covered / len(rows):.0f} %).', '', '| Service specification (tag) | Served | Total |', '|---|---:|---:|']
    for tag, items in by_tag.items():
        out.append(f'| {tag} | {sum(1 for r in items if r["served"])} | {len(items)} |')
    missing = [r for r in rows if not r['served']]
    out += ['', '## Not served', '']
    out += [f'- `{r["method"]} {r["path"]}` ({r["operationId"]})' for r in missing] or ['None.']
    out += ['', '## Served through repository superpaths', '',
            'The standalone single-shell and single-submodel interfaces are served at their repository mount points:', '']
    via = collections.Counter(r['via'] for r in rows if r['via'])
    out += [f'- `/{k}/{{id}}/...`: {v} operations' for k, v in sorted(via.items())]
    router = Forge(Config(database=':memory:')).api.router
    out += ['', '## aasforge extensions (no counterpart in this collection)', '']
    out += [f'- `{m} {p}`' for m, p in extensions(router, spec)]
    return '\n'.join(out) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('spec')
    parser.add_argument('-o', '--output')
    parser.add_argument('--source', default='', help='provenance note, e.g. repository and commit')
    args = parser.parse_args(argv)
    spec = yaml.safe_load(Path(args.spec).read_text())
    rows = analyse(spec)
    text = report(spec, rows, Path(args.spec).stem, args.source)
    if args.output:
        Path(args.output).write_text(text)
    else:
        sys.stdout.write(text)
    return 0 if all(r['served'] for r in rows) else 1


if __name__ == '__main__':
    sys.exit(main())
