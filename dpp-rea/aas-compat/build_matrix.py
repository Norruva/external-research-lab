"""Merge per-tool result files into one Markdown compatibility matrix.

Usage: python3 build_matrix.py results/ > MATRIX.md

Expects in results/: fingerprints.json, results-python.json, results-aas4j-1.0.5.json,
results-aas4j-2.0.2.json, results-dotnet.json and probes-manifest.json.
"""
import json
import sys
from pathlib import Path

base = Path(sys.argv[1])
load = lambda name: json.loads((base / name).read_text())
fingerprints = {f['file']: f for f in load('fingerprints.json')}
rows = load('results-python.json') + load('results-aas4j-1.0.5.json') + load('results-aas4j-2.0.2.json') \
    + load('results-dotnet.json')
probes = load('probes-manifest.json')
by_file = {}
for row in rows:
    by_file.setdefault(row['file'], {}).setdefault(row['tool'], []).append(row)


def native_version(path):
    namespaces = fingerprints.get(path, {}).get('xml_namespaces') or []
    if namespaces:
        return namespaces[0]
    name = path.lower()
    if path.startswith('probes/'):
        return probes.get(Path(path).stem, {}).get('introduced', '3.0').replace('-only', '')
    return '3.1' if any(k in name for k in ('v3.1', '02035', '02099', '02080')) else '3.0'


def cell(results):
    if not results:
        return '–'
    worst = max(results, key=lambda r: r['status'] != 'pass')
    if worst['status'] != 'pass':
        return '✗'
    objects = worst.get('objects')
    expected = worst.get('expected_objects')
    if objects is not None and expected and objects < expected:
        return f'⚠ {objects}/{expected}'
    errors = worst.get('verification_errors')
    if errors:
        return f'✓ ({errors} verif.)'
    return '✓'


COLUMNS = [
    ('Schema (own version)', lambda t, v: t.get({'3.0': 'schema-v3.0.9', '3.1': 'schema-v3.1.2',
                                                  '3.2': 'schema-v3.2.0'}.get(v, 'schema-v3.0.9'))),
    ('aas-core Py (own version)', lambda t, v: t.get({'3.0': 'aas-core3.0-python-1.1.4'}.get(
        v, 'aas-core3.1-python-1.0.0'))),
    ('BaSyx Py strict', lambda t, v: t.get('basyx-python-2.2.0-aasx-strict') or t.get('basyx-python-2.2.0-strict')),
    ('BaSyx Py default', lambda t, v: t.get('basyx-python-2.2.0-aasx-default') or t.get('basyx-python-2.2.0-default')),
    ('AAS4J 1.0.5', lambda t, v: t.get('aas4j-1.0.5')),
    ('AAS4J 2.0.2', lambda t, v: t.get('aas4j-2.0.2')),
    ('AASX Server lib', lambda t, v: t.get('aasx-server-lib-b092dbe')),
]

print('# AAS cross-tool compatibility matrix\n')
print('Generated by `build_matrix.py`. ✓ read without error; ✗ rejected; ⚠ n/m reported success but kept only '
      'n of m identifiables; "(k verif.)" loaded but the tool\'s own verifier reported k constraint errors. '
      'Schema and aas-core columns use the file\'s own metamodel version (XML namespace, file name, or probe '
      'manifest); 3.2 files are checked with aas-core 3.1 because no 3.2 SDK is published yet.\n')
print('| File | Ver. | ' + ' | '.join(c for c, _ in COLUMNS) + ' |')
print('|---|---|' + '---|' * len(COLUMNS))
for path in sorted(by_file, key=lambda p: (not p.startswith('probes/'), p)):
    tools = by_file[path]
    version = native_version(path)
    name = path.split('/')[-1]
    print(f'| `{name}` | {version} | ' + ' | '.join(cell(fn(tools, version)) for _, fn in COLUMNS) + ' |')
