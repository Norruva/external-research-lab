"""Build the battery passport field-coverage matrix from the attribute list and viewer mapping.

Usage: python3 build_matrix.py > MATRIX.md
"""
import collections
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
attributes = json.loads((HERE / 'battery-pass-attributes-v1.2.json').read_text())['attributes']
mapping = json.loads((HERE / 'mapping.json').read_text())

VIEWERS = (('cx', 'ev', 'Tractus-X viewer (EV)'), ('proto', 'lmt', 'LMT prototype'))
ACCESS = {'Public': 'Public',
          'persons with a legitimate interest': 'Legit. interest',
          'persons with a legitimate interest and the Commission': 'Legit. interest + Commission',
          'Notified bodies, market surveillance authorities and the Commission': 'Authorities'}


def tally(viewer, column, access=None):
    counts = collections.Counter()
    for a in attributes:
        if a[column] != 'x' or (access and a['access'] != access):
            continue
        counts[mapping[a['id']][viewer][0]] += 1
    return counts


def pct(counts):
    total = sum(counts.values())
    return f"{counts['Y']}/{total} full, {counts['P']} partial, {counts['N']} missing" if total else 'n/a'


print('# Battery passport field-coverage matrix\n')
print('Generated by `build_matrix.py` from `battery-pass-attributes-v1.2.json` and `mapping.json`.')
print('Legend: **Y** structured field, **P** partial (document/free text, coarser, or missing a required split), '
      '**N** absent, **-** not applicable to that battery category. '
      'Mandatory flags (x = mandatory, o = voluntary) come from the Battery Pass longlist v1.2.\n')
print('## Coverage of mandatory attributes\n')
print('| Access tier | ' + ' | '.join(v[2] for v in VIEWERS) + ' |')
print('|---|' + '---|' * len(VIEWERS))
for access, label in [(None, 'All tiers')] + list(ACCESS.items()):
    print(f'| {label if access is None else ACCESS[access]} | ' +
          ' | '.join(pct(tally(v, c, access)) for v, c, _ in VIEWERS) + ' |')
print('\n## Attribute matrix\n')
print('| # | Attribute | Access | EV | LMT | Regulation reference | Tractus-X | Prototype | Tractus-X path / note |')
print('|---|---|---|---|---|---|---|---|---|')
for a in attributes:
    m = mapping[a['id']]
    print(f"| {a['id']} | {a['attribute']} | {ACCESS[a['access']]} | {a['ev'] or ' '} | {a['lmt'] or ' '} | "
          f"{a['regulation_reference'].replace('|', '/')} | {m['cx'][0]} | {m['proto'][0]} | `{m['cx'][1]}` |"
          if m['cx'][1] else
          f"| {a['id']} | {a['attribute']} | {ACCESS[a['access']]} | {a['ev'] or ' '} | {a['lmt'] or ' '} | "
          f"{a['regulation_reference'].replace('|', '/')} | {m['cx'][0]} | {m['proto'][0]} | |")
